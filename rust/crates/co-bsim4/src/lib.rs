/// Reuse the charge/capacitance fields produced by the final floating-point
/// load. The legacy path repeats that same operating point in `MODEINITSMSIG`
/// before `acLoad`; set `CIRCUITOPT_BSIM_REUSE_SMSIG_LOAD=0` to restore it for
/// numerical A/B checks. The raw `dc` entry point always retains the reload as
/// an in-process oracle.
fn reuse_loaded_small_signal() -> bool {
    static REUSE: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *REUSE.get_or_init(|| {
        std::env::var_os("CIRCUITOPT_BSIM_REUSE_SMSIG_LOAD")
            .map(|value| {
                let value = value.to_string_lossy();
                let value = value.trim();
                !(value.is_empty()
                    || value == "0"
                    || value.eq_ignore_ascii_case("false")
                    || value.eq_ignore_ascii_case("no"))
            })
            .unwrap_or(true)
    })
}

/// Select the maximum converged internal-node correction for final-load reuse,
/// honoring explicit process-level A/B overrides.
///
/// Production entries currently pass `default = false`, preserving the exact
/// reload unless the internal solution was already bit-identical. The numeric
/// tolerance override supports bounded transient A/B runs; the older boolean
/// switch retains its all-or-nothing behavior. Raw `dc` always reloads and
/// remains the in-process oracle.
fn final_load_reuse_tolerance(default: bool) -> f64 {
    static TOLERANCE: std::sync::OnceLock<Option<f64>> = std::sync::OnceLock::new();
    TOLERANCE
        .get_or_init(|| {
            if let Some(value) = std::env::var_os("CIRCUITOPT_BSIM_FINAL_LOAD_TOL") {
                let parsed = value.to_string_lossy().trim().parse::<f64>().ok();
                return parsed.filter(|value| value.is_finite() && *value >= 0.0);
            }
            std::env::var_os("CIRCUITOPT_BSIM_REUSE_FINAL_LOAD").map(|value| {
                let value = value.to_string_lossy();
                let value = value.trim();
                if value.is_empty()
                    || value == "0"
                    || value.eq_ignore_ascii_case("false")
                    || value.eq_ignore_ascii_case("no")
                {
                    0.0
                } else {
                    f64::INFINITY
                }
            })
        })
        .unwrap_or(if default { f64::INFINITY } else { 0.0 })
}

/// Process-level kill switch for the D6 acLoad-skip. `CIRCUIT_BSIM4_FULL_EVAL`
/// set to a truthy value (anything but empty / `0` / `false` / `no`) forces the
/// DC-Newton path back to the full small-signal extraction. Read once and cached
/// for the process lifetime.
pub fn full_eval_forced() -> bool {
    static FORCED: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *FORCED.get_or_init(|| {
        std::env::var_os("CIRCUIT_BSIM4_FULL_EVAL")
            .map(|value| {
                let value = value.to_string_lossy();
                let value = value.trim();
                !(value.is_empty()
                    || value == "0"
                    || value.eq_ignore_ascii_case("false")
                    || value.eq_ignore_ascii_case("no"))
            })
            .unwrap_or(false)
    })
}

pub unsafe fn noise(
    device: *mut CoBsim4,
    frequency_hz: f64,
    total_real: *mut f64,
    total_imag: *mut f64,
    flicker_real: *mut f64,
    flicker_imag: *mut f64,
) -> c_int {
    // `!(f > 0.0)` (not the "cleaner" `f <= 0.0`) is deliberate host.c parity:
    // it also rejects NaN, which `<=` would accept.
    #[allow(clippy::neg_cmp_op_on_partial_ord)]
    if device.is_null() || (*device).setup_done == 0 || !(frequency_hz > 0.0) {
        return E_BADPARM;
    }
    let _guard = lock_device(device);

    let mut external = [0 as c_int; CO_TERMINALS];
    let mut internal = [0 as c_int; CO_MAX_INTERNAL];
    let internal_count = device_nodes(device, &mut external, &mut internal);
    if internal_count < 0 {
        return E_UNSUPP;
    }
    let internal_count = internal_count as usize;

    (*device).ckt.CKTomega = 2.0 * CO_PI * frequency_hz;
    co_clear(device);
    let status = ffi::BSIM4v5acLoad(
        addr_of_mut!((*device).model).cast(),
        addr_of_mut!((*device).ckt),
    );
    if status != OK {
        return status;
    }

    let mut job: ffi::NOISEAN = std::mem::zeroed();
    let mut data: ffi::Ndata = std::mem::zeroed();
    job.NstartFreq = frequency_hz;
    data.freq = frequency_hz;
    data.GainSqInv = 1.0;
    (*device).noise_source_count = 0;
    let previous_job = (*device).ckt.CKTcurJob;
    (*device).ckt.CKTcurJob = addr_of_mut!(job).cast();
    ACTIVE_NOISE_DEVICE.with(|active| active.set(device));
    let mut total_density = 0.0f64;
    let status = ffi::BSIM4v5noise(
        N_DENS,
        N_CALC,
        addr_of_mut!((*device).model).cast(),
        addr_of_mut!((*device).ckt),
        &mut data,
        &mut total_density,
    );
    ACTIVE_NOISE_DEVICE.with(|active| active.set(null_mut()));
    (*device).ckt.CKTcurJob = previous_job;
    if status != OK {
        return status;
    }

    let mut total = [[CoComplex::ZERO; CO_TERMINALS]; CO_TERMINALS];
    let mut flicker = [[CoComplex::ZERO; CO_TERMINALS]; CO_TERMINALS];

    for source_index in 0..(*device).noise_source_count as usize {
        let source = (*device).noise_sources[source_index];
        if !source.density.is_finite() || source.density < 0.0 {
            return E_PARMVAL;
        }
        if source.density == 0.0 {
            continue;
        }

        let mut external_incidence = [CoComplex::ZERO; CO_TERMINALS];
        let mut internal_incidence = [CoComplex::ZERO; CO_MAX_INTERNAL];
        for terminal in 0..CO_TERMINALS {
            if source.node1 == external[terminal] {
                external_incidence[terminal].real += 1.0;
            }
            if source.node2 == external[terminal] {
                external_incidence[terminal].real -= 1.0;
            }
        }
        for index in 0..internal_count {
            if source.node1 == internal[index] {
                internal_incidence[index].real += 1.0;
            }
            if source.node2 == internal[index] {
                internal_incidence[index].real -= 1.0;
            }
        }

        let mut internal_voltage = [CoComplex::ZERO; CO_MAX_INTERNAL];
        if internal_count > 0 {
            let mut system = [[CoComplex::ZERO; CO_MAX_INTERNAL]; CO_MAX_INTERNAL];
            for row in 0..internal_count {
                for col in 0..internal_count {
                    system[row][col] = matrix_value(device, internal[row], internal[col]);
                }
            }
            let status = solve_complex(
                internal_count,
                &system,
                &internal_incidence,
                &mut internal_voltage,
            );
            if status != OK {
                return status;
            }
        }

        let mut reduced = [CoComplex::ZERO; CO_TERMINALS];
        for terminal in 0..CO_TERMINALS {
            reduced[terminal] = external_incidence[terminal];
            for index in 0..internal_count {
                reduced[terminal] = reduced[terminal].sub(
                    matrix_value(device, external[terminal], internal[index])
                        .mul(internal_voltage[index]),
                );
            }
        }
        for row in 0..CO_TERMINALS {
            for col in 0..CO_TERMINALS {
                let mut contribution = reduced[row].mul(reduced[col].conjugate());
                contribution.real *= source.density;
                contribution.imag *= source.density;
                total[row][col] = total[row][col].add(contribution);
                if source.index == BSIM4V5_FLNOIZ {
                    flicker[row][col] = flicker[row][col].add(contribution);
                }
            }
        }
    }

    for row in 0..CO_TERMINALS {
        for col in 0..CO_TERMINALS {
            let offset = row * CO_TERMINALS + col;
            *total_real.add(offset) = total[row][col].real;
            *total_imag.add(offset) = total[row][col].imag;
            *flicker_real.add(offset) = flicker[row][col].real;
            *flicker_imag.add(offset) = flicker[row][col].imag;
        }
    }
    OK
}

const EVAL_BATCH_PARALLEL_MIN: usize = 8;
const EVAL_BATCH_DEFAULT_MAX_THREADS: usize = 10;

thread_local! {
    /// Whether this thread evaluates device batches inline instead of handing
    /// them to the shared pool. See [`SerialEvalGuard`].
    static SERIAL_EVAL: Cell<bool> = const { Cell::new(false) };
}

/// Marks the calling thread as already running inside a parallel region, so its
/// device batches are evaluated inline.
///
/// The batch pool speeds up one isolated transient, but it is a single process-
/// wide pool: when several transients run at once — signoff PVT points, a ramp
/// of SAR conversions, Monte-Carlo trials — every one of them submits into it,
/// and the pool becomes the funnel. Measured on the reference machine, sixteen
/// TSMC28 MDAC residue transients took 4.90 s on one thread while keeping 7.8
/// cores busy, and eight threads only reached 4.03 s because there was no idle
/// core left to give them. The same sixteen with inline evaluation took 10.54 s
/// on one thread but 3.19 s on eight, at 6.0 cores. So the outer level should
/// claim the parallelism and the inner one should step aside.
///
/// Evaluation order does not affect results — each slot is written
/// independently — so this only changes scheduling.
#[must_use = "the scope ends when the guard is dropped"]
pub struct SerialEvalGuard {
    previous: bool,
}

impl SerialEvalGuard {
    /// Evaluate this thread's device batches inline until the guard is dropped.
    pub fn enter() -> Self {
        Self {
            previous: SERIAL_EVAL.with(|flag| flag.replace(true)),
        }
    }
}

impl Drop for SerialEvalGuard {
    fn drop(&mut self) {
        SERIAL_EVAL.with(|flag| flag.set(self.previous));
    }
}

/// Kill switch: `CIRCUITOPT_BSIM_NESTED_POOL=1` keeps the pool even inside a
/// serial-eval scope, restoring the pre-change scheduling for A/B runs.
fn nested_pool_forced() -> bool {
    static FORCED: OnceLock<bool> = OnceLock::new();
    *FORCED.get_or_init(|| {
        std::env::var("CIRCUITOPT_BSIM_NESTED_POOL")
            .map(|value| value != "0")
            .unwrap_or(false)
    })
}

fn serial_eval_requested() -> bool {
    SERIAL_EVAL.with(Cell::get) && !nested_pool_forced()
}

/// Reusable storage for full four-terminal BSIM evaluation batches.
///
/// One workspace belongs to one transient evaluator. Handles and statuses are
/// allocated once, while each Newton iteration borrows the caller-owned,
/// lifetime-reused terminal and result arrays.
pub struct EvalBatchWorkspace {
    handles: Vec<usize>,
    groups: Vec<EvalBatchGroup>,
    statuses: Vec<c_int>,
    final_load_tolerance: f64,
    bypass_voltage_tolerance: f64,
}

struct EvalBatchGroup {
    handle: usize,
    indices: Vec<usize>,
}

/// One preallocated output slot for a full four-terminal BSIM evaluation.
///
/// `repr(C)` deliberately matches `co_core::bsim_transient::Evaluation`; the
/// PyO3 bridge verifies size and alignment before casting that reusable array.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct EvalBatchResult {
    pub currents: [f64; CO_TERMINALS],
    pub conductance: [f64; CO_TERMINALS * CO_TERMINALS],
    pub charges: [f64; CO_TERMINALS],
    pub capacitance: [f64; CO_TERMINALS * CO_TERMINALS],
}

impl EvalBatchWorkspace {
    /// # Safety
    ///
    /// Every non-zero handle must remain live for the complete workspace
    /// lifetime. Repeated handles are allowed and are evaluated serially within
    /// one worker; distinct handles must refer to independent instances.
    pub unsafe fn new(handles: Vec<usize>) -> Self {
        unsafe { Self::new_with_final_load_tolerance(handles, 0.0) }
    }

    /// Build a workspace whose transient entries may omit a final private-node
    /// reload below `final_load_tolerance`.
    ///
    /// # Safety
    ///
    /// The handle lifetime and exclusivity contract is the same as [`Self::new`].
    pub unsafe fn new_with_final_load_tolerance(
        handles: Vec<usize>,
        final_load_tolerance: f64,
    ) -> Self {
        unsafe { Self::new_with_transient_tolerances(handles, final_load_tolerance, 0.0) }
    }

    /// Build a workspace with transient-only compact-model tolerances.
    ///
    /// # Safety
    ///
    /// The handle lifetime and exclusivity contract is the same as [`Self::new`].
    pub unsafe fn new_with_transient_tolerances(
        handles: Vec<usize>,
        final_load_tolerance: f64,
        bypass_voltage_tolerance: f64,
    ) -> Self {
        let count = handles.len();
        let mut group_for_handle = HashMap::with_capacity(count);
        let mut groups: Vec<EvalBatchGroup> = Vec::with_capacity(count);
        for (index, &handle) in handles.iter().enumerate() {
            let group_index = *group_for_handle.entry(handle).or_insert_with(|| {
                groups.push(EvalBatchGroup {
                    handle,
                    indices: Vec::new(),
                });
                groups.len() - 1
            });
            groups[group_index].indices.push(index);
        }
        Self {
            handles,
            groups,
            statuses: vec![OK; count],
            final_load_tolerance,
            bypass_voltage_tolerance,
        }
    }

    pub fn len(&self) -> usize {
        self.handles.len()
    }

    pub fn is_empty(&self) -> bool {
        self.handles.is_empty()
    }

    pub fn handle(&self, index: usize) -> Option<usize> {
        self.handles.get(index).copied()
    }

    pub fn statuses(&self) -> &[c_int] {
        &self.statuses
    }
}

fn eval_batch_thread_count() -> usize {
    let requested = std::env::var("CIRCUITOPT_BSIM_BATCH_THREADS")
        .ok()
        .and_then(|value| value.parse::<usize>().ok())
        .or_else(|| {
            std::env::var("RAYON_NUM_THREADS")
                .ok()
                .and_then(|value| value.parse::<usize>().ok())
        })
        .or_else(|| std::thread::available_parallelism().ok().map(usize::from))
        .unwrap_or(1);
    requested.clamp(1, EVAL_BATCH_DEFAULT_MAX_THREADS)
}

fn eval_batch_pool() -> Option<&'static ThreadPool> {
    static POOL: OnceLock<Option<ThreadPool>> = OnceLock::new();
    POOL.get_or_init(|| {
        let threads = eval_batch_thread_count();
        if threads > 1 {
            ThreadPoolBuilder::new()
                .num_threads(threads)
                .thread_name(|index| format!("co-bsim4-{index}"))
                .build()
                .ok()
        } else {
            None
        }
    })
    .as_ref()
}

fn eval_batch_slot(
    handle: usize,
    terminals: &[f64; CO_TERMINALS],
    result: &mut EvalBatchResult,
    status: &mut c_int,
    transient: bool,
    final_load_tolerance: f64,
    bypass_voltage_tolerance: f64,
) {
    *status = unsafe {
        if transient {
            eval_vp_transient_with_tolerances(
                handle as *mut CoBsim4,
                terminals.as_ptr(),
                result.currents.as_mut_ptr(),
                result.conductance.as_mut_ptr(),
                result.charges.as_mut_ptr(),
                result.capacitance.as_mut_ptr(),
                final_load_tolerance,
                bypass_voltage_tolerance,
            )
        } else {
            eval_vp(
                handle as *mut CoBsim4,
                terminals.as_ptr(),
                result.currents.as_mut_ptr(),
                result.conductance.as_mut_ptr(),
                result.charges.as_mut_ptr(),
                result.capacitance.as_mut_ptr(),
            )
        }
    };
}

unsafe fn eval_batch_into_configured(
    workspace: &mut EvalBatchWorkspace,
    terminals: &[[f64; CO_TERMINALS]],
    results: &mut [EvalBatchResult],
    transient: bool,
) -> c_int {
    if workspace.len() != terminals.len() || workspace.len() != results.len() {
        return E_BADPARM;
    }
    if workspace.is_empty() {
        return OK;
    }

    let handles = &workspace.handles;
    let groups = &workspace.groups;
    let statuses = &mut workspace.statuses;
    let final_load_tolerance = workspace.final_load_tolerance;
    let bypass_voltage_tolerance = workspace.bypass_voltage_tolerance;

    let ran_parallel =
        if handles.len() >= EVAL_BATCH_PARALLEL_MIN && groups.len() > 1 && !serial_eval_requested()
        {
            let Some(pool) = eval_batch_pool() else {
                return eval_batch_serial(
                    handles,
                    terminals,
                    results,
                    statuses,
                    transient,
                    final_load_tolerance,
                    bypass_voltage_tolerance,
                );
            };
            let results_address = results.as_mut_ptr() as usize;
            let statuses_address = statuses.as_mut_ptr() as usize;
            pool.install(|| {
                groups.par_iter().for_each(|group| {
                    for &index in &group.indices {
                        // Workspace construction places every slot in exactly
                        // one group. Groups run in parallel, while repeated
                        // uses of one mutable BSIM handle stay serial.
                        let result =
                            unsafe { &mut *((results_address as *mut EvalBatchResult).add(index)) };
                        let status = unsafe { &mut *((statuses_address as *mut c_int).add(index)) };
                        eval_batch_slot(
                            group.handle,
                            &terminals[index],
                            result,
                            status,
                            transient,
                            final_load_tolerance,
                            bypass_voltage_tolerance,
                        );
                    }
                });
            });
            true
        } else {
            false
        };
    if !ran_parallel {
        return eval_batch_serial(
            handles,
            terminals,
            results,
            statuses,
            transient,
            final_load_tolerance,
            bypass_voltage_tolerance,
        );
    }
    statuses
        .iter()
        .copied()
        .find(|status| *status != OK)
        .unwrap_or(OK)
}

/// Evaluate one terminal row per persistent handle directly into reusable slots.
///
/// This compatibility path matches public scalar [`eval`] semantics.
///
/// # Safety
///
/// All handles retained by `workspace` must still be live. Distinct handle
/// values must refer to independent instances.
pub unsafe fn eval_batch_into(
    workspace: &mut EvalBatchWorkspace,
    terminals: &[[f64; CO_TERMINALS]],
    results: &mut [EvalBatchResult],
) -> c_int {
    eval_batch_into_configured(workspace, terminals, results, false)
}

/// Exclusive-handle transient hot-loop variant of [`eval_batch_into`].
///
/// It has a distinct entry for future transient-only policies while preserving
/// the same workspace and output layout. Final-load reuse remains opt-in through
/// `CIRCUITOPT_BSIM_REUSE_FINAL_LOAD=1`.
///
/// # Safety
///
/// In addition to the base workspace contract, every distinct handle must be
/// exclusively owned by this transient for the complete call. Repeated handles
/// are allowed and remain serial within one workspace group.
pub unsafe fn eval_batch_into_transient(
    workspace: &mut EvalBatchWorkspace,
    terminals: &[[f64; CO_TERMINALS]],
    results: &mut [EvalBatchResult],
) -> c_int {
    eval_batch_into_configured(workspace, terminals, results, true)
}

#[allow(clippy::too_many_arguments)]
fn eval_batch_serial(
    handles: &[usize],
    terminals: &[[f64; CO_TERMINALS]],
    results: &mut [EvalBatchResult],
    statuses: &mut [c_int],
    transient: bool,
    final_load_tolerance: f64,
    bypass_voltage_tolerance: f64,
) -> c_int {
    for index in 0..handles.len() {
        eval_batch_slot(
            handles[index],
            &terminals[index],
            &mut results[index],
            &mut statuses[index],
            transient,
            final_load_tolerance,
            bypass_voltage_tolerance,
        );
    }
    statuses
        .iter()
        .copied()
        .find(|status| *status != OK)
        .unwrap_or(OK)
}

/// Compatibility batch ABI. New Rust callers should retain an
/// [`EvalBatchWorkspace`] and call [`eval_batch_into`] for every Newton round.
#[allow(clippy::too_many_arguments)]
pub unsafe fn eval_batch(
    devices: *const *mut CoBsim4,
    count: usize,
    terminals: *const f64,
    currents: *mut f64,
    conductance: *mut f64,
    charges: *mut f64,
    capacitance: *mut f64,
    statuses: *mut c_int,
) -> c_int {
    if count == 0 {
        return OK;
    }
    if devices.is_null()
        || terminals.is_null()
        || currents.is_null()
        || conductance.is_null()
        || charges.is_null()
        || capacitance.is_null()
    {
        return E_BADPARM;
    }
    let handles: Vec<usize> = std::slice::from_raw_parts(devices, count)
        .iter()
        .map(|handle| *handle as usize)
        .collect();
    if handles.contains(&0) {
        return E_BADPARM;
    }
    let terminal_rows = std::slice::from_raw_parts(terminals.cast::<[f64; CO_TERMINALS]>(), count);
    let mut workspace = EvalBatchWorkspace::new(handles);
    let mut results = vec![EvalBatchResult::default(); count];
    let first_error = eval_batch_into(&mut workspace, terminal_rows, &mut results);
    for (index, result) in results.iter().enumerate() {
        std::ptr::copy_nonoverlapping(
            result.currents.as_ptr(),
            currents.add(index * CO_TERMINALS),
            CO_TERMINALS,
        );
        std::ptr::copy_nonoverlapping(
            result.conductance.as_ptr(),
            conductance.add(index * CO_TERMINALS * CO_TERMINALS),
            CO_TERMINALS * CO_TERMINALS,
        );
        std::ptr::copy_nonoverlapping(
            result.charges.as_ptr(),
            charges.add(index * CO_TERMINALS),
            CO_TERMINALS,
        );
        std::ptr::copy_nonoverlapping(
            result.capacitance.as_ptr(),
            capacitance.add(index * CO_TERMINALS * CO_TERMINALS),
            CO_TERMINALS * CO_TERMINALS,
        );
    }
    if !statuses.is_null() {
        std::ptr::copy_nonoverlapping(workspace.statuses.as_ptr(), statuses, count);
    }
    first_error
}

/// Batch noise evaluation over independent, already-biased handles.
///
/// Frequencies for one handle are evaluated serially because BSIM stores the
/// latest AC/noise scratch in the handle. Independent handles are distributed
/// through Rayon; results are copied out in device-major, frequency-major order.
#[allow(clippy::too_many_arguments)]
pub unsafe fn noise_batch(
    devices: *const *mut CoBsim4,
    count: usize,
    frequencies: *const f64,
    frequency_count: usize,
    total_real: *mut f64,
    total_imag: *mut f64,
    flicker_real: *mut f64,
    flicker_imag: *mut f64,
    statuses: *mut c_int,
) -> c_int {
    struct DeviceNoise {
        status: c_int,
        total_real: Vec<[f64; CO_TERMINALS * CO_TERMINALS]>,
        total_imag: Vec<[f64; CO_TERMINALS * CO_TERMINALS]>,
        flicker_real: Vec<[f64; CO_TERMINALS * CO_TERMINALS]>,
        flicker_imag: Vec<[f64; CO_TERMINALS * CO_TERMINALS]>,
    }

    if count == 0 || frequency_count == 0 {
        return OK;
    }
    if devices.is_null()
        || frequencies.is_null()
        || total_real.is_null()
        || total_imag.is_null()
        || flicker_real.is_null()
        || flicker_imag.is_null()
    {
        return E_BADPARM;
    }
    let handles: Vec<usize> = (0..count)
        .map(|index| *devices.add(index) as usize)
        .collect();
    if handles.contains(&0) {
        return E_BADPARM;
    }
    let frequencies = std::slice::from_raw_parts(frequencies, frequency_count).to_vec();

    let evaluate = |handle: &usize| {
        let mut result = DeviceNoise {
            status: OK,
            total_real: Vec::with_capacity(frequency_count),
            total_imag: Vec::with_capacity(frequency_count),
            flicker_real: Vec::with_capacity(frequency_count),
            flicker_imag: Vec::with_capacity(frequency_count),
        };
        for &frequency in &frequencies {
            let mut tr = [0.0; CO_TERMINALS * CO_TERMINALS];
            let mut ti = [0.0; CO_TERMINALS * CO_TERMINALS];
            let mut fr = [0.0; CO_TERMINALS * CO_TERMINALS];
            let mut fi = [0.0; CO_TERMINALS * CO_TERMINALS];
            let status = noise(
                *handle as *mut CoBsim4,
                frequency,
                tr.as_mut_ptr(),
                ti.as_mut_ptr(),
                fr.as_mut_ptr(),
                fi.as_mut_ptr(),
            );
            result.total_real.push(tr);
            result.total_imag.push(ti);
            result.flicker_real.push(fr);
            result.flicker_imag.push(fi);
            if status != OK {
                result.status = status;
                break;
            }
        }
        result
    };
    let results: Vec<DeviceNoise> = if count >= 2 && !serial_eval_requested() {
        handles.par_iter().map(evaluate).collect()
    } else {
        handles.iter().map(evaluate).collect()
    };

    let matrix_size = CO_TERMINALS * CO_TERMINALS;
    let mut first_error = OK;
    for (device_index, result) in results.iter().enumerate() {
        if !statuses.is_null() {
            *statuses.add(device_index) = result.status;
        }
        if first_error == OK && result.status != OK {
            first_error = result.status;
        }
        for frequency_index in 0..result.total_real.len() {
            let offset = (device_index * frequency_count + frequency_index) * matrix_size;
            std::ptr::copy_nonoverlapping(
                result.total_real[frequency_index].as_ptr(),
                total_real.add(offset),
                matrix_size,
            );
            std::ptr::copy_nonoverlapping(
                result.total_imag[frequency_index].as_ptr(),
                total_imag.add(offset),
                matrix_size,
            );
            std::ptr::copy_nonoverlapping(
                result.flicker_real[frequency_index].as_ptr(),
                flicker_real.add(offset),
                matrix_size,
            );
            std::ptr::copy_nonoverlapping(
                result.flicker_imag[frequency_index].as_ptr(),
                flicker_imag.add(offset),
                matrix_size,
            );
        }
    }
    first_error
}

