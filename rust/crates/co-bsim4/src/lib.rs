// Dense linear solves (host.c `co_solve_real` / `co_solve_complex`), ported with
// identical partial-pivoting and elimination order for bit-level parity.
// ---------------------------------------------------------------------------

unsafe fn co_clear(device: *mut CoBsim4) {
    if full_frame_clear_forced() {
        std::ptr::write_bytes(
            addr_of_mut!((*device).matrix) as *mut u8,
            0,
            std::mem::size_of::<MatrixFrame>(),
        );
        (*device).rhs = [0.0; CO_MAX_NODES];
        (*device).irhs = [0.0; CO_MAX_NODES];
        return;
    }
    // The vendor only stamps nodes allocated through CKTmkVolt, whose largest
    // index is CKTmaxEqNum, so entries beyond it stay zero and are never read.
    // One BSIM instance uses far fewer than CO_MAX_NODES, and this runs once
    // per model load, which is the whole cost of an evaluation.
    //
    // Clearing the active block beats one contiguous frame memset under every
    // schedule, not only the outer-parallel one: the frame is 24x24 complex
    // entries while an instance needs a corner of it. Clearing whole active
    // rows instead (one memset, still half the frame) measured inside run-to-
    // run noise of this loop, so the narrower block is kept for the smaller
    // footprint.
    let active = ((*device).ckt.CKTmaxEqNum + 1).clamp(1, CO_MAX_NODES as c_int) as usize;
    for row in 0..active {
        std::ptr::write_bytes((*device).matrix.value[row].as_mut_ptr(), 0, active);
    }
    std::ptr::write_bytes((*device).rhs.as_mut_ptr(), 0, active);
    std::ptr::write_bytes((*device).irhs.as_mut_ptr(), 0, active);
}

fn env_flag(name: &'static str) -> bool {
    std::env::var_os(name)
        .map(|value| {
            let value = value.to_string_lossy();
            matches!(
                value.trim().to_ascii_lowercase().as_str(),
                "1" | "true" | "yes" | "on"
            )
        })
        .unwrap_or(false)
}

/// Kill switch: `CIRCUITOPT_BSIM_FULL_FRAME_CLEAR=1` restores the whole-frame
/// memset for A/B runs. Both paths leave the same values behind.
fn full_frame_clear_forced() -> bool {
    static FORCED: OnceLock<bool> = OnceLock::new();
    *FORCED.get_or_init(|| env_flag("CIRCUITOPT_BSIM_FULL_FRAME_CLEAR"))
}

fn solve_real(
    size: usize,
    matrix: &[[f64; CO_MAX_INTERNAL]; CO_MAX_INTERNAL],
    rhs: &[f64; CO_MAX_INTERNAL],
    solution: &mut [f64; CO_MAX_INTERNAL],
) -> c_int {
    let mut work = *matrix;
    let mut values = *rhs;

    for pivot in 0..size {
        let mut best = pivot;
        let mut magnitude = work[pivot][pivot].abs();
        for row in (pivot + 1)..size {
            let candidate = work[row][pivot].abs();
            if candidate > magnitude {
                magnitude = candidate;
                best = row;
            }
        }
        if magnitude < 1.0e-30 {
            return E_PANIC;
        }
        if best != pivot {
            for col in pivot..size {
                let temporary = work[pivot][col];
                work[pivot][col] = work[best][col];
                work[best][col] = temporary;
            }
            values.swap(pivot, best);
        }
        for row in (pivot + 1)..size {
            let factor = work[row][pivot] / work[pivot][pivot];
            work[row][pivot] = 0.0;
            for col in (pivot + 1)..size {
                // host.c `work[row][col] -= factor * work[pivot][col]`; clang
                // (-ffp-contract=on) fuses this to an FMA — match it exactly.
                work[row][col] = (-factor).mul_add(work[pivot][col], work[row][col]);
            }
            values[row] = (-factor).mul_add(values[pivot], values[row]);
        }
    }
    for row in (0..size).rev() {
        let mut value = values[row];
        for col in (row + 1)..size {
            value = (-work[row][col]).mul_add(solution[col], value);
        }
        solution[row] = value / work[row][row];
    }
    OK
}

