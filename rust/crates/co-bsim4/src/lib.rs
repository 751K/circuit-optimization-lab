#[inline]
unsafe fn matrix_value(device: *const CoBsim4, row: c_int, col: c_int) -> CoComplex {
    CoComplex {
        real: (*device).matrix.value[row as usize][col as usize][0],
        imag: (*device).matrix.value[row as usize][col as usize][1],
    }
}

unsafe fn discover_device_nodes(
    device: *const CoBsim4,
    external: &mut [c_int; CO_TERMINALS],
    internal: &mut [c_int; CO_MAX_INTERNAL],
) -> c_int {
    external[0] = (*device).instance.BSIM4v5dNode;
    external[1] = (*device).instance.BSIM4v5gNodeExt;
    external[2] = (*device).instance.BSIM4v5sNode;
    external[3] = (*device).instance.BSIM4v5bNode;
    let candidates = [
        (*device).instance.BSIM4v5dNodePrime,
        (*device).instance.BSIM4v5gNodePrime,
        (*device).instance.BSIM4v5gNodeMid,
        (*device).instance.BSIM4v5sNodePrime,
        (*device).instance.BSIM4v5bNodePrime,
        (*device).instance.BSIM4v5dbNode,
        (*device).instance.BSIM4v5sbNode,
    ];
    let mut count: usize = 0;
    for &node in candidates.iter() {
        let is_external = external.contains(&node);
        let duplicate = internal[..count].contains(&node);
        if node > 0 && !is_external && !duplicate {
            if count >= CO_MAX_INTERNAL {
                return -1;
            }
            internal[count] = node;
            count += 1;
        }
    }
    count as c_int
}

unsafe fn device_nodes(
    device: *const CoBsim4,
    external: &mut [c_int; CO_TERMINALS],
    internal: &mut [c_int; CO_MAX_INTERNAL],
) -> c_int {
    if (*device).setup_done != 0 {
        *external = (*device).external_nodes;
        *internal = (*device).internal_nodes;
        (*device).internal_count
    } else {
        discover_device_nodes(device, external, internal)
    }
}

// ---------------------------------------------------------------------------
// DC + small-signal core (host.c `co_bsim4_dc`). Requires the lock to be held.
// ---------------------------------------------------------------------------

/// Small-signal extraction tail of `co_bsim4_dc`: optional legacy
/// `MODEINITSMSIG` reload, terminal charge read-back, and `acLoad` plus complex
/// Schur reduction yielding the 4x4 terminal capacitance. The final floating
/// load already filled the same instance fields, so production evaluation
/// reuses them; raw `dc` requests the reload as an oracle. Split out of
/// `dc_inner` so the DC-Newton path can skip the whole tail (D6 acLoad-skip).
/// Requires the lock held and the DC operating point already loaded.
unsafe fn extract_small_signal(
    device: *mut CoBsim4,
    external: &[c_int; CO_TERMINALS],
    internal: &[c_int; CO_MAX_INTERNAL],
    internal_count: usize,
    charges: *mut f64,
    capacitance: *mut f64,
    reload_operating_point: bool,
) -> c_int {
    if reload_operating_point {
        (*device).ckt.CKTmode = MODEDCOP | MODEINITSMSIG;
        co_clear(device);
        let status = ffi::BSIM4v5load(
            addr_of_mut!((*device).model).cast(),
            addr_of_mut!((*device).ckt),
        );
        if status != OK {
            return status;
        }
    }
    let state_base = (*device).instance.BSIM4v5states;
    *charges.add(0) = (*device).state0[(state_base + OFF_QD) as usize];
    *charges.add(1) = (*device).state0[(state_base + OFF_QG) as usize];
    *charges.add(2) = (*device).state0[(state_base + OFF_QS) as usize];
    *charges.add(3) = (*device).state0[(state_base + OFF_QB) as usize];
    if (*device).instance.BSIM4v5rbodyMod != 0 {
        *charges.add(3) += (*device).state0[(state_base + OFF_QBD) as usize];
        *charges.add(3) += (*device).state0[(state_base + OFF_QBS) as usize];
    }
    let model_type = (*device).model.BSIM4v5type as f64;
    for terminal in 0..CO_TERMINALS {
        *charges.add(terminal) *= model_type;
    }

    (*device).ckt.CKTomega = 1.0;
    co_clear(device);
    let status = ffi::BSIM4v5acLoad(
        addr_of_mut!((*device).model).cast(),
        addr_of_mut!((*device).ckt),
    );
    if status != OK {
        return status;
    }
    let mut internal_solutions = [[CoComplex::ZERO; CO_MAX_INTERNAL]; CO_TERMINALS];
    if internal_count > 0 {
        let mut system = [[CoComplex::ZERO; CO_MAX_INTERNAL]; CO_MAX_INTERNAL];
        for i in 0..internal_count {
            for j in 0..internal_count {
                system[i][j] = matrix_value(device, internal[i], internal[j]);
            }
        }
        let mut rights = [[CoComplex::ZERO; CO_MAX_INTERNAL]; CO_TERMINALS];
        for (col, right) in rights.iter_mut().enumerate() {
            for i in 0..internal_count {
                right[i] = matrix_value(device, internal[i], external[col]);
            }
        }
        let status =
            solve_complex_columns(internal_count, &system, &rights, &mut internal_solutions);
        if status != OK {
            return status;
        }
    }
    for row in 0..CO_TERMINALS {
        for col in 0..CO_TERMINALS {
            let mut reduced = matrix_value(device, external[row], external[col]);
            for i in 0..internal_count {
                reduced = reduced.sub(
                    matrix_value(device, external[row], internal[i])
                        .mul(internal_solutions[col][i]),
                );
            }
            *capacitance.add(row * CO_TERMINALS + col) = reduced.imag;
        }
    }
    OK
}

#[allow(clippy::too_many_arguments)]
unsafe fn dc_inner(
    device: *mut CoBsim4,
    terminals: *const f64,
    currents: *mut f64,
    conductance: *mut f64,
    charges: *mut f64,
    capacitance: *mut f64,
    op: *mut f64,
    want_caps: bool,
    final_load_reuse_tolerance: f64,
    reload_small_signal: bool,
) -> c_int {
    if device.is_null() || (*device).setup_done == 0 {
        return E_BADPARM;
    }
    let term = [
        *terminals.add(0),
        *terminals.add(1),
        *terminals.add(2),
        *terminals.add(3),
    ];

    let mut external = [0 as c_int; CO_TERMINALS];
    let mut internal = [0 as c_int; CO_MAX_INTERNAL];
    let internal_count = device_nodes(device, &mut external, &mut internal);
    if internal_count < 0 {
        return E_UNSUPP;
    }
    let internal_count = internal_count as usize;

    for i in 0..CO_TERMINALS {
        (*device).rhs_old[external[i] as usize] = term[i];
    }
    if internal_count >= 1 && (*device).rhs_old[internal[0] as usize] == 0.0 {
        (*device).rhs_old[internal[0] as usize] = term[0];
    }
    if internal_count >= 2 && (*device).rhs_old[internal[1] as usize] == 0.0 {
        (*device).rhs_old[internal[1] as usize] = term[2];
    }

    (*device).ckt.CKTmode = MODEDCOP | MODEINITFLOAT;
    let mut loaded_at_final_internal_state = internal_count == 0;
    let mut final_internal_error = 0.0;
    let state_base = (*device).instance.BSIM4v5states as usize;
    let mut state_before = [0.0f64; LIMITED_STATE_COUNT];
    for iteration in 0..40 {
        co_clear(device);
        // The vendor answers "do not treat this bias as converged" through
        // CKTnoncon (b4v5ld.c): it fires when the limiter clamped the voltages
        // this load was asked for -- `DEVfetlim` / `DEVlimvds` / `DEVpnjlim`
        // against the previous call's `CKTstate0` -- and when the previous
        // linearization failed to predict this point's terminal currents. Both
        // mean the returned operating point is not the one at `term`. Zero it
        // first so the flag describes this load alone rather than the whole
        // handle's history.
        (*device).ckt.CKTnoncon = 0;
        for (offset, slot) in state_before.iter_mut().enumerate() {
            *slot = (*device).state0[state_base + offset];
        }
        let status = ffi::BSIM4v5load(
            addr_of_mut!((*device).model).cast(),
            addr_of_mut!((*device).ckt),
        );
        if status != OK {
            return status;
        }
        // CKTnoncon alone is not sufficient: `DEVfetlim` limits silently, and
        // the rbodyMod branch of the junction limiting overwrites the
        // `DEVpnjlim` flag of the core vbs/vbd with the flags of the body-net
        // junctions alone (b4v5ld.c "Check = 0"). A limiter that is still
        // walking always betrays itself in `CKTstate0`, though: each load
        // stores the voltages it actually used, at least one limiting step
        // away from the previous ones. Requiring that block to stand still
        // closes the gap -- without it, an evaluation whose internal nodes are
        // insensitive to the walking voltage can exit on the node criterion
        // mid-walk and report an operating point nobody asked for.
        let mut limiter_settled = true;
        for (offset, before) in state_before.iter().enumerate() {
            let delta = (*device).state0[state_base + offset] - before;
            // `!(<=)` (not `>`) is deliberate: a NaN must count as unsettled
            // and run into the iteration cap instead of converging.
            #[allow(clippy::neg_cmp_op_on_partial_ord)]
            if !(delta.abs() <= LIMITER_SETTLE_TOL) {
                limiter_settled = false;
                break;
            }
        }
        // Re-loading walks the limiter in, because each load stores the
        // voltages it settled on and the next one limits against those.
        let model_unconverged = (*device).ckt.CKTnoncon != 0 || !limiter_settled;
        if internal_count == 0 {
            if !model_unconverged {
                break;
            }
            if iteration + 1 == 40 {
                return E_PANIC;
            }
            continue;
        }

        let mut system = [[0.0f64; CO_MAX_INTERNAL]; CO_MAX_INTERNAL];
        let mut right = [0.0f64; CO_MAX_INTERNAL];
        let mut next = [0.0f64; CO_MAX_INTERNAL];
        for row in 0..internal_count {
            right[row] = (*device).rhs[internal[row] as usize];
            for j in 0..CO_TERMINALS {
                let m = (*device).matrix.value[internal[row] as usize][external[j] as usize][0];
                right[row] = (-m).mul_add(term[j], right[row]);
            }
            for col in 0..internal_count {
                system[row][col] =
                    (*device).matrix.value[internal[row] as usize][internal[col] as usize][0];
            }
        }
        let status = solve_real(internal_count, &system, &right, &mut next);
        if status != OK {
            return status;
        }
        let mut error = 0.0f64;
        let mut unchanged = true;
        for i in 0..internal_count {
            let previous = (*device).rhs_old[internal[i] as usize];
            error = error.max((next[i] - previous).abs());
            unchanged &= next[i].to_bits() == previous.to_bits();
            (*device).rhs_old[internal[i] as usize] = next[i];
        }
        final_internal_error = error;
        // Settled internal nodes are not enough on their own: they can stop
        // moving while the limiter still holds the bias away from `term`, and
        // the operating point would then be silently reported for voltages
        // nobody asked for.
        if !model_unconverged && error < 1.0e-12 {
            loaded_at_final_internal_state = unchanged;
            break;
        }
        if iteration == 39 {
            return E_PANIC;
        }
    }

    // This reload lands within `final_internal_error` of a load the loop just
    // accepted as unlimited, and that bound is below every limiting threshold,
    // so it cannot re-arm the limiter.
    if !loaded_at_final_internal_state && final_internal_error > final_load_reuse_tolerance {
        co_clear(device);
        let status = ffi::BSIM4v5load(
            addr_of_mut!((*device).model).cast(),
            addr_of_mut!((*device).ckt),
        );
        if status != OK {
            return status;
        }
    }

    for row in 0..CO_TERMINALS {
        let r = external[row] as usize;
        let mut residual = -(*device).rhs[r];
        for col in 0..CO_TERMINALS {
            let m = (*device).matrix.value[r][external[col] as usize][0];
            residual = m.mul_add(term[col], residual);
        }
        for col in 0..internal_count {
            let m = (*device).matrix.value[r][internal[col] as usize][0];
            residual = m.mul_add((*device).rhs_old[internal[col] as usize], residual);
        }
        *currents.add(row) = residual;
    }

    let mut internal_solutions = [[0.0f64; CO_MAX_INTERNAL]; CO_TERMINALS];
    if internal_count > 0 {
        let mut system = [[0.0f64; CO_MAX_INTERNAL]; CO_MAX_INTERNAL];
        for i in 0..internal_count {
            for j in 0..internal_count {
                system[i][j] =
                    (*device).matrix.value[internal[i] as usize][internal[j] as usize][0];
            }
        }
        let mut rights = [[0.0f64; CO_MAX_INTERNAL]; CO_TERMINALS];
        for (col, right) in rights.iter_mut().enumerate() {
            for i in 0..internal_count {
                right[i] = (*device).matrix.value[internal[i] as usize][external[col] as usize][0];
            }
        }
        let status = solve_real_columns(internal_count, &system, &rights, &mut internal_solutions);
        if status != OK {
            return status;
        }
    }
    for row in 0..CO_TERMINALS {
        for col in 0..CO_TERMINALS {
            let mut reduced =
                (*device).matrix.value[external[row] as usize][external[col] as usize][0];
            for i in 0..internal_count {
                let m = (*device).matrix.value[external[row] as usize][internal[i] as usize][0];
                reduced = (-m).mul_add(internal_solutions[col][i], reduced);
            }
            *conductance.add(row * CO_TERMINALS + col) = reduced;
        }
    }

    if want_caps {
        let status = extract_small_signal(
            device,
            &external,
            &internal,
            internal_count,
            charges,
            capacitance,
            reload_small_signal,
        );
        if status != OK {
            return status;
        }
    } else {
        // DC-Newton fast path (D6 acLoad-skip): the caller consumes currents and
        // conductance only, so skip the MODEINITSMSIG reload + `acLoad`
        // capacitance extraction entirely. Zero the unused charge/capacitance
        // outputs so the result is deterministic regardless of prior handle state.
        for terminal in 0..CO_TERMINALS {
            *charges.add(terminal) = 0.0;
        }
        for offset in 0..CO_TERMINALS * CO_TERMINALS {
            *capacitance.add(offset) = 0.0;
        }
    }

    *op.add(0) = (*device).instance.BSIM4v5cd;
    *op.add(1) = (*device).instance.BSIM4v5gm;
    *op.add(2) = (*device).instance.BSIM4v5gds;
    *op.add(3) = (*device).instance.BSIM4v5gmbs;
    *op.add(4) = (*device).instance.BSIM4v5von;
    *op.add(5) = (*device).instance.BSIM4v5vdsat;
    *op.add(6) = (*device).instance.BSIM4v5ueff;
    *op.add(7) = internal_count as f64;
    OK
}

/// In-C conservation snap (host.c `co_bsim4_enforce_terminal_conservation`).
unsafe fn enforce_terminal_conservation(
    currents: *mut f64,
    conductance: *mut f64,
    charges: *mut f64,
    capacitance: *mut f64,
) -> c_int {
    let mut current_error: f64 = 0.0;
    let mut current_scale: f64 = 1.0e-18;
    let mut charge_error: f64 = 0.0;
    let mut charge_scale: f64 = 1.0e-24;
    for terminal in 0..CO_TERMINALS {
        current_error += *currents.add(terminal);
        current_scale = current_scale.max((*currents.add(terminal)).abs());
        charge_error += *charges.add(terminal);
        charge_scale = charge_scale.max((*charges.add(terminal)).abs());
    }
    if current_error.abs() > (1.0e-8 * current_scale).max(1.0e-9) {
        return E_PANIC;
    }
    if charge_error.abs() > (1.0e-8 * charge_scale).max(1.0e-18) {
        return E_PANIC;
    }
    *currents.add(CO_TERMINALS - 1) -= current_error;
    *charges.add(CO_TERMINALS - 1) -= charge_error;

    let mut conductance_scale: f64 = 1.0e-18;
    let mut capacitance_scale: f64 = 1.0e-24;
    for offset in 0..CO_TERMINALS * CO_TERMINALS {
        conductance_scale = conductance_scale.max((*conductance.add(offset)).abs());
        capacitance_scale = capacitance_scale.max((*capacitance.add(offset)).abs());
    }
    for column in 0..CO_TERMINALS {
        let mut conductance_error: f64 = 0.0;
        let mut capacitance_error: f64 = 0.0;
        for row in 0..CO_TERMINALS {
            conductance_error += *conductance.add(row * CO_TERMINALS + column);
            capacitance_error += *capacitance.add(row * CO_TERMINALS + column);
        }
        if conductance_error.abs() > (1.0e-8 * conductance_scale).max(1.0e-9) {
            return E_PANIC;
        }
        if capacitance_error.abs() > (1.0e-8 * capacitance_scale).max(1.0e-18) {
            return E_PANIC;
        }
        *conductance.add((CO_TERMINALS - 1) * CO_TERMINALS + column) -= conductance_error;
        *capacitance.add((CO_TERMINALS - 1) * CO_TERMINALS + column) -= capacitance_error;
    }
    OK
}

